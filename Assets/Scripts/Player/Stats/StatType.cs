namespace Game.Stats
{
    /// <summary>
    /// Базовые характеристики персонажа, к которым может применяться
    /// StatModifier. Производные величины (итоговый объём маны, значение защиты)
    /// сюда не входят — они всегда пересчитываются CharacterStats из этих базовых значений.
    ///
    /// ВАЖНО: порядок значений сериализуется в ассетах как число — новые
    /// характеристики добавлять ТОЛЬКО в конец.
    /// </summary>
    public enum StatType
    {
        Strength,
        Stamina,
        Mana,
        MagicDamage,
        Speed,
        CarryWeight,
        Defense,

        /// <summary>
        /// Бонус к физическому урону. Flat — процентные пункты (25 = +25%, суммируются с бонусом от силы).
        /// Percent — множитель на весь физический урон (+20 = ×1.2, −10 = ×0.9).
        /// </summary>
        PhysicalDamageBonus,

        /// <summary>Скорость регенерации выносливости (ед/сек). Percent +25 = регенерация на 25% быстрее.</summary>
        StaminaRegen,

        /// <summary>Множитель трат выносливости (база 1). Percent −15 = траты ×0.85.</summary>
        StaminaCost,

        /// <summary>Множитель скорости каста (база 1). Percent +20 = каст и восстановление после него на 20% быстрее.</summary>
        CastSpeed
    }
}
