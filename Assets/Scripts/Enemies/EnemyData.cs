using UnityEngine;
using Game.Combat;
using Game.Items;
using Game.Progression;
using Game.Stats;

namespace Game.Enemies
{
    /// <summary>
    /// Статическое описание ТИПА врага. Не хранит runtime state.
    /// Новый враг = новый ассет EnemyData + префаб с набором компонентов.
    /// </summary>
    [CreateAssetMenu(fileName = "NewEnemyData", menuName = "Game/Enemies/Enemy Data")]
    public class EnemyData : ScriptableObject
    {
        [Tooltip("Название врага для себя и будущего UI. На логику не влияет.")]
        public string enemyName;

        [TextArea]
        [Tooltip("Заметки для себя: роль врага, на каких локациях встречается, на что рассчитан. Например: «Начальные локации: простой ближний враг, 1 атака, низкий poise». На логику не влияет.")]
        public string designNotes;

        [Header("Stats")]
        [Tooltip("ГЛАВНЫЙ источник характеристик врага: EnemyController при запуске заменяет ими BaseCharacterStats на префабе (в CharacterStats префаба это поле — только запасное). Ассет BaseCharacterStats — те же характеристики, что у игрока. Здоровье = baseHealth + strength × healthPerStrengthPoint. ... (остальной текст без изменений)")]
        public BaseCharacterStats baseStats;

        [Tooltip("Сопротивления врага: физическое и магическое (%), урон каждой стихии (100 — обычный, 0 — иммунитет, 200 — слабость) и сопротивление статус-эффектам. Пусто — враг не имеет никаких сопротивлений (всё 0%).")]
        public ResistanceProfileData resistanceProfile;

        [Tooltip("Награда за убийство: опыт и валюта (RewardData). Выдаётся игроку автоматически в момент смерти врага.")]
        public RewardData reward;

        [Header("Weapon")]
        [Tooltip("Оружие, от которого ближние атаки врага берут стихию, стихийный урон, эффекты при попадании (яд, ожог) и базовую дальность (range). Сам физический урон, тайминги и размер хитбокса берутся из AttackData в списке атак. Можно оставить пустым у чистых магов — тогда ближние атаки без стихии, с дальностью по умолчанию 1.5 м.")]
        public WeaponData weapon;

        [Header("Attacks")]
        [Tooltip("Набор атак врага. Каждая запись — либо ближняя атака (AttackData), либо заклинание (SpellData), с минимальной и максимальной дистанцией, кулдауном и весом. Из доступных сейчас атак враг выбирает случайную, с учётом веса. Простые враги — одна-две атаки; сложные — несколько с разными дистанциями, тяжёлыми непарируемыми ударами и заклинаниями.")]
        public EnemyAttackOption[] attacks;

        [Min(0f)]
        [Tooltip("На каком расстоянии от цели враг останавливается и ждёт возможности ударить (метры, по горизонтали). 0 = автоматически: 90% дальности самой короткой атаки, то есть ближний враг подходит вплотную, а маг с единственным заклинанием останавливается на дистанции каста. Задавайте вручную, если враг должен держать дистанцию побольше (например, лучник).")]
        public float engageDistance = 0f;

        [Min(0f)]
        [Tooltip("Минимальная пауза (секунды) между окончанием одной атаки и началом следующей. Из диапазона Min–Max выбирается случайное значение. Чем меньше пауза, тем агрессивнее враг; у простых врагов около 1–2 с, у сложных можно 0.3–0.6 с.")]
        public float postAttackDelayMin = 0.6f;

        [Min(0f)]
        [Tooltip("Максимальная пауза (секунды) между атаками. Должна быть не меньше Min. Разброс между Min и Max делает ритм врага менее предсказуемым.")]
        public float postAttackDelayMax = 1.4f;

        [Header("Movement")]
        [Range(0.1f, 2f)]
        [Tooltip("Скорость патруля как доля от характеристики Speed (0.5 = вполовину, спокойная ходьба). Влияет на ходьбу по точкам патруля и возвращение домой.")]
        public float patrolSpeedMultiplier = 0.5f;

        [Range(0.1f, 2f)]
        [Tooltip("Скорость, с которой враг идёт проверять шум или последнюю известную позицию игрока, как доля от Speed. Обычно между патрулём и погоней (около 0.7).")]
        public float investigateSpeedMultiplier = 0.7f;

        [Range(0.1f, 2f)]
        [Tooltip("Скорость погони как доля от Speed. 1 — как указано в характеристиках. Больше 1 — враг быстрее своей базовой скорости (убегать от него труднее). Игрок ходит со скоростью 5 без бега, поэтому враг со Speed×множитель больше 5 догонит его.")]
        public float chaseSpeedMultiplier = 1f;

        [Tooltip("Скорость поворота врага, градусов в секунду. 360 — полный оборот за секунду. Малое значение (90–180) делает врага неповоротливым: его можно обойти сбоку, и он долго разворачивается к игроку. Влияет и на то, как долго он может следить за целью во время замаха.")]
        public float turnSpeed = 360f;

        [Min(0f)]
        [Tooltip("Высота полёта в метрах. 0 — наземный враг. Больше 0 — летающий: модель висит на этой высоте над NavMesh. Летающие враги всё равно двигаются только над запечённой поверхностью NavMesh, то есть не могут лететь над пропастью.")]
        public float hoverHeight = 0f;

        [Header("Perception")]
        [Min(0f)]
        [Tooltip("Дальность зрения прямо перед собой, метры. Внутри зоны VisibilityZone (например, туман) умножается на её множитель. Стены и другие преграды закрывают обзор. Для простых врагов 8–12 м, для чутких 20 и больше.")]
        public float sightRange = 15f;

        [Range(10f, 360f)]
        [Tooltip("Полный угол поля зрения в градусах. 110 означает, что враг видит на полную дальность ±55° от направления взгляда. Вне этого угла дальность падает (см. боковое и заднее зрение). 360 — враг видит одинаково во все стороны.")]
        public float fieldOfView = 110f;

        [Range(0f, 1f)]
        [Tooltip("Доля дальности зрения на самом краю поля зрения, то есть боковое зрение. 0.6 при дальности 15 м даёт 9 м. Дальше от края к спине дальность плавно падает до значения «заднее зрение».")]
        public float sideRangeMultiplier = 0.6f;

        [Range(0f, 1f)]
        [Tooltip("Доля дальности зрения прямо за спиной врага. 0.15 при дальности 15 м даёт 2.25 м: к такому врагу можно подкрасться сзади. 0 — сзади совсем не видит (кроме радиуса близкого обнаружения).")]
        public float rearRangeMultiplier = 0.15f;

        [Min(0f)]
        [Tooltip("Радиус, метры, в пределах которого враг замечает цель в любом направлении, даже за спиной, если между ними нет преград. Имитирует чутьё на очень близкую цель. 0 — без этого. Не уменьшается туманом.")]
        public float closeAwarenessRadius = 2f;

        [Min(0f)]
        [Tooltip("Сколько секунд цель должна быть непрерывно видна, прежде чем враг её заметит и перейдёт в погоню. 0 — замечает мгновенно. 0.5–1 с даёт игроку шанс мельком пересечь поле зрения и скрыться. Если цель пропала из виду раньше, отсчёт сбрасывается.")]
        public float reactionTime = 0.25f;

        [Min(0f)]
        [Tooltip("Сколько секунд без визуального контакта враг ещё «помнит» цель и продолжает погоню к последней известной точке. По истечении теряет цель и идёт на осмотр этой точки (Investigate), потом возвращается домой. Не действует для врагов в режиме NeverLoseTarget и AlwaysHunting.")]
        public float loseTargetDelay = 4f;

        [Min(0f)]
        [Tooltip("Чуткость слуха. Шум громкости L слышен на расстоянии L × это значение (громкость в NoiseService.Emit — радиус в метрах). 1 — как есть, 0 — глухой, 2 — слышит вдвое дальше. Услышав шум, враг идёт проверять его источник.")]
        public float hearingSensitivity = 1f;

        [Header("Idle / Patrol")]
        [Min(0f)]
        [Tooltip("Радиус случайного патруля вокруг стартовой точки врага (метры). 0 — патруля нет, враг стоит на месте. Используется только если у экземпляра на сцене НЕ заданы точки патруля (waypoints): точки экземпляра важнее этого параметра. Точки выбираются только на NavMesh.")]
        public float patrolRadius = 0f;

        [Min(0f)]
        [Tooltip("Минимальное время (секунды), которое враг стоит в состоянии Idle, прежде чем отправиться в патруль. Из диапазона Min–Max выбирается случайное значение. Если патруля нет, враг просто продолжает стоять.")]
        public float idleTimeMin = 1f;

        [Min(0f)]
        [Tooltip("Максимальное время (секунды) стояния в Idle перед патрулём. Не меньше Min.")]
        public float idleTimeMax = 3f;

        [Min(0f)]
        [Tooltip("Минимальное время (секунды), которое враг стоит в каждой точке патруля перед переходом к следующей. Из диапазона Min–Max выбирается случайное значение.")]
        public float patrolWaitMin = 1f;

        [Min(0f)]
        [Tooltip("Максимальное время (секунды) ожидания в точке патруля. Не меньше Min.")]
        public float patrolWaitMax = 3f;

        [Header("Investigate")]
        [Min(0f)]
        [Tooltip("Сколько секунд враг осматривается на месте, куда пришёл проверить шум или последнюю позицию игрока. Он поворачивается влево–вправо один раз за это время. Не нашёл цель — возвращается в Idle и идёт домой. Чем больше время, тем дольше в этой точке опасно прятаться.")]
        public float lookAroundDuration = 3f;

        [Range(0f, 180f)]
        [Tooltip("На какой угол влево и вправо от исходного направления враг поворачивает голову при осмотре (градусы). 60 — осматривает сектор около 120°. 180 — осматривается во все стороны.")]
        public float lookAroundAngle = 60f;

        [Header("Stagger (poise)")]
        [Tooltip("Если включено, враг не реагирует на удары и парирование (боссы, тяжёлая броня): его невозможно оглушить или прервать его атаку. Урон по нему проходит как обычно.")]
        public bool immuneToStagger = false;

        [Min(0f)]
        [Tooltip("Через сколько секунд без попаданий накопленный урон по устойчивости сбрасывается, и запас восстанавливается полностью. Заставляет игрока наносить удары подряд, чтобы оглушить врага. Меньше — враг сбивается реже, больше — серия ударов копится дольше.")]
        public float poiseResetDelay = 3f;

        [Min(1f)]
        [Tooltip("Устойчивость во время собственной атаки. Пока враг атакует, входящий staggerPower делится на это число: при значении 2 лёгкий удар по замахивающемуся врагу действует вдвое слабее. 1 — враг сбивается так же, как стоя. Большие значения не дают сбить замах слабым ударом, поэтому игроку нужно либо уклоняться, либо парировать, либо бить тяжёлым.")]
        public float attackingPoiseMultiplier = 2f;

        [Min(0f)]
        [Tooltip("Сколько секунд враг оглушён после сломанной устойчивости: стоит, не двигается и не атакует, текущая атака отменяется. 0.4–0.6 с — короткая реакция на удар, 1 с и больше — окно для серии ударов.")]
        public float staggerDuration = 0.6f;

        [Min(0f)]
        [Tooltip("Сколько секунд враг оглушён после успешного парирования его атаки игроком. Парирование оглушает всегда, независимо от запаса устойчивости (кроме врагов с «Immune To Stagger»), поэтому значение обычно больше обычного оглушения: это награда игроку за точный тайминг, окно для сильного удара.")]
        public float parryStaggerDuration = 1.5f;

        [Header("Death")]
        [Tooltip("Префаб, который появляется на месте смерти врага: кучка пепла, груда костей и т.д. Сам враг при этом удаляется. Пусто — остаётся сам объект врага: его коллайдеры и ИИ отключены, а по истечении времени жизни трупа он удаляется. Префаб трупа не должен содержать скриптов ИИ.")]
        public GameObject corpsePrefab;

        [Min(0f)]
        [Tooltip("Через сколько секунд труп (или сам враг, если префаб трупа не задан) исчезает со сцены. Нужен для оптимизации: большие значения оставляют на локации много объектов. Награда выдаётся в момент смерти, не по истечении этого времени.")]
        public float corpseLifetime = 20f;

        private void OnValidate()
        {
            if (baseStats == null)
            {
                Debug.LogWarning($"EnemyData '{name}': не назначен baseStats — враг возьмёт характеристики из префаба.", this);
            }
            if (attacks == null) return;

            for (int i = 0; i < attacks.Length; i++)
            {
                EnemyAttackOption option = attacks[i];
                if (option == null) continue;

                bool hasAttack = option.attack != null;
                bool hasSpell = option.spell != null;
                if (hasAttack == hasSpell)
                {
                    Debug.LogWarning($"EnemyData '{name}': в атаке #{i} нужно указать ровно одно — attack или spell.", this);
                }
                if (option.weight == 0)
                {
                    Debug.LogWarning($"EnemyData '{name}': в атаке #{i} нужно указать weight.", this);
                }
            }
        }
    }
}